#!/usr/bin/env python3
"""PlatformIO pre-build script: stamp the firmware with identity.

Bumps of the flash path have silently left boards on old firmware more than
once, so the build writes include/firmware_version.h and the firmware prints
that stamp at boot and in its periodic status line. `./flash.sh version` reads
it back off a running board, which is the only trustworthy answer to "is the
new firmware actually on this device?".

The header is only rewritten when its content changes, so it does not force a
rebuild on every invocation.
"""

from __future__ import annotations

import datetime
import os
import subprocess

Import("env")  # noqa: F821 - SCons/PlatformIO injected

PROJECT_DIR = env.subst("$PROJECT_DIR")  # noqa: F821  .../firmware
ROOT_DIR = os.path.dirname(PROJECT_DIR)
OUT_PATH = os.path.join(PROJECT_DIR, "include", "firmware_version.h")


def read_version() -> str:
    # CI sets FW_VERSION from the release tag. Writing the tag into VERSION
    # instead would leave the tree modified and stamp every release "-dirty".
    override = os.environ.get("FW_VERSION", "").strip().lstrip("v")
    if override:
        return override
    try:
        with open(os.path.join(ROOT_DIR, "VERSION"), encoding="utf-8") as handle:
            return handle.read().strip() or "0.0.0"
    except OSError:
        return "0.0.0"


def git(*args: str) -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", ROOT_DIR, *args],
            stderr=subprocess.DEVNULL,
            text=True,
        ).strip()
    except Exception:
        return ""


def main() -> None:
    version = read_version()
    sha = git("rev-parse", "--short", "HEAD") or "nogit"
    dirty = "-dirty" if git("status", "--porcelain") else ""
    now = datetime.datetime.now(datetime.timezone.utc)
    # The build time is part of the id, not just of the banner: without it two
    # builds of the same commit are indistinguishable, and "is the new firmware
    # really on this board?" cannot be answered from the device.
    firmware_id = f"v{version}+{sha}{dirty}-b{now.strftime('%H%M%S')}"
    stamp = now.strftime("%Y-%m-%dT%H:%M:%SZ")

    header = f"""// Generated by tools/gen_version.py - do not edit by hand.
#pragma once

#define FW_VERSION "{version}"
#define FW_GIT_SHA "{sha}"
#define FW_BUILD_STAMP "{stamp}"
#define FW_ID "{firmware_id}"
#define FW_BANNER "power-meter firmware {firmware_id} built {stamp}"
#define FW_TOKEN "FW:{firmware_id}"
"""

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    try:
        with open(OUT_PATH, encoding="utf-8") as handle:
            if handle.read() == header:
                return
    except OSError:
        pass

    with open(OUT_PATH, "w", encoding="utf-8") as handle:
        handle.write(header)

    print(f"[version] {firmware_id} built {stamp}")


main()
